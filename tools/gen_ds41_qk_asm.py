#!/usr/bin/env python3
"""Generates src/hip_ds41_attention_qk.inc: the 4-heads-per-wave QK half tile (8 keys) of attention_chunk_kernel as
one inline asm block with fixed registers so that every FMA pair dual-issues (VOPD). Same arithmetic as the C form:
per (head, key) one fmaf chain over the lane's 16 dims in order, the first step fma(q, k, +0) (v_fmaak 0).
Registers: q head h at QB[h] + i (QB = 0, 17, 34, 51: distinct banks within the pairs 0/1 and 2/3), key a (even slot) at
68 + i, key b (odd slot) at 85 + i (banks differ), results T(h, jj) = 102 + 8 (jj / 2) + 2 h + jj % 2 (key a even, b odd).
VOPD pairs per dim i of a key pair: (h0 a, h1 b), (h1 a, h0 b), (h2 a, h3 b), (h3 a, h2 b).
Key slot jj is read at LDS (ka ^ (jj << 11)) + tb + 512 g (g = dims 4 g .. 4 g + 3); the next pair's group g is requested
once the current pair's group g is consumed (lgkmcnt: the 6 later requests may be in flight)."""
import sys

QB = [0, 17, 34, 51]
KA, KB, T0 = 68, 85, 102
ADDR = [16, 33]   # address registers of key a / key b of a pair
BS = chr(92)      # backslash


def T(h, jj):
    return T0 + 8 * (jj // 2) + 2 * h + jj % 2


L = []


def addr(p):
    for s in range(2):
        jj = 2 * p + s
        L.append(f"v_add_nc_u32 v{ADDR[s]}, %1, %2" if jj == 0 else f"v_xad_u32 v{ADDR[s]}, %1, {hex(jj << 11)}, %2")


def load(g):
    for s, kb in ((0, KA), (1, KB)):
        L.append(f"ds_load_b128 v[{kb + 4 * g}:{kb + 4 * g + 3}], v{ADDR[s]}" + (f" offset:{512 * g}" if g else ""))


addr(0)
for g in range(4):
    load(g)
for p in range(4):
    for g in range(4):
        later = 2 * (3 - g) + (2 * g if p < 3 else 0)
        L.append(f"s_waitcnt lgkmcnt({later})")
        for i in range(4 * g, 4 * g + 4):
            for (ha, hb) in ((0, 1), (1, 0), (2, 3), (3, 2)):
                x = (T(ha, 2 * p), QB[ha] + i, KA + i)
                y = (T(hb, 2 * p + 1), QB[hb] + i, KB + i)
                if i == 0:
                    L.append(f"v_dual_fmaak_f32 v{x[0]}, v{x[1]}, v{x[2]}, 0x0 :: v_dual_fmaak_f32 v{y[0]}, v{y[1]}, v{y[2]}, 0x0")
                else:
                    L.append(f"v_dual_fmac_f32 v{x[0]}, v{x[1]}, v{x[2]} :: v_dual_fmac_f32 v{y[0]}, v{y[1]}, v{y[2]}")
        if p < 3:
            if g == 0:
                addr(p + 1)
            load(g)
clob = ", ".join(f'"v{r}"' for r in ADDR + list(range(KA, KA + 16)) + list(range(KB, KB + 16)))
out = ["// generated by tools/gen_ds41_qk_asm.py (do not edit): see attention_tile, STRIX_DS41_ATTN_LEAN 4",
       "#define DS41_QK_ASM_TEXT " + BS]
out += [f'    "{l}{BS}n" {BS}' for l in L]
out += ['    ""', f"#define DS41_QK_ASM_CLOBBERS {clob}"]
open(sys.argv[1], "w", newline="\n").write("\n".join(out) + "\n")
print(len(L), "lines")
