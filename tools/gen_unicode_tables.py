#!/usr/bin/env python3
"""Generate src/serve/unicode_tables.inc: code point ranges of the general categories the BPE
pre-tokenizer pattern uses (L letters, M marks, N numbers), one flag set per maximal range.

usage: gen_unicode_tables.py OUT.inc
"""
import sys
import unicodedata

FLAGS = {'L': 1, 'M': 2, 'N': 4}


def main(out_path):
    ranges = []
    current = None
    for cp in range(0x110000):
        flags = FLAGS.get(unicodedata.category(chr(cp))[0], 0)
        if current and current[2] == flags and current[1] + 1 == cp:
            current[1] = cp
            continue
        if current and current[2]:
            ranges.append(tuple(current))
        current = [cp, cp, flags]
    if current and current[2]:
        ranges.append(tuple(current))
    with open(out_path, 'w', encoding='utf-8', newline='\n') as out:
        out.write('// Generated by tools/gen_unicode_tables.py from Unicode %s. Do not edit.\n' % unicodedata.unidata_version)
        out.write('// {first, last, flags}: 1 letter (L), 2 mark (M), 4 number (N).\n')
        out.write('inline constexpr UnicodeRange kUnicodeRanges[] = {\n')
        for first, last, flags in ranges:
            out.write('    {0x%X, 0x%X, %d},\n' % (first, last, flags))
        out.write('};\n')
        out.write('inline constexpr const char* kUnicodeVersion = "%s";\n' % unicodedata.unidata_version)
    print(len(ranges), 'ranges, Unicode', unicodedata.unidata_version)


if __name__ == '__main__':
    main(sys.argv[1])
