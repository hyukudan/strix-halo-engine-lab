#!/usr/bin/env python3
"""Generate src/serve/unicode_tables.inc: code point ranges of the general categories the BPE
pre-tokenizer patterns use (L letters, M marks, N numbers, P punctuation, S symbols), one flag set per
maximal range.

usage: gen_unicode_tables.py OUT.inc
"""
import sys
import unicodedata
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from unicode_ranges import nonzero_ranges, require_pinned_ucd

FLAGS = {'L': 1, 'M': 2, 'N': 4, 'P': 8, 'S': 16}


def category_flags(cp):
    category = unicodedata.category(chr(cp))
    return FLAGS.get(category[0], 0) | (32 if category == 'Nd' else 0)


def main(out_path):
    require_pinned_ucd()
    ranges = list(nonzero_ranges(category_flags))
    with open(out_path, 'w', encoding='utf-8', newline='\n') as out:
        out.write('// Generated by tools/gen_unicode_tables.py from Unicode %s. Do not edit.\n' % unicodedata.unidata_version)
        out.write('// {first, last, flags}: 1 letter (L), 2 mark (M), 4 number (N), 8 punctuation (P), 16 symbol (S), 32 decimal digit (Nd).\n')
        out.write('inline constexpr UnicodeRange kUnicodeRanges[] = {\n')
        for first, last, flags in ranges:
            out.write('    {0x%X, 0x%X, %d},\n' % (first, last, flags))
        out.write('};\n')
        out.write('inline constexpr const char* kUnicodeVersion = "%s";\n' % unicodedata.unidata_version)
    print(len(ranges), 'ranges, Unicode', unicodedata.unidata_version)


if __name__ == '__main__':
    main(sys.argv[1])
