#!/usr/bin/env python3
# Generates src/hip_hc_wide2_vopd.inc: one 128-feature chunk of the register-permuted wide HC
# split-K projection (16 rows x 8 outputs x 4 features per lane = 512 FMAs) as hand-paired VOPD.
#
# Each accumulator acc(q, p) runs its chain acc = fma(x(q, j), c(p, j), acc) for j = 0, 1, 2, 3 in
# this order (v_dual_fmac_f32: the single-rounding FMA of the C++ fmaf form). A VOPD pair is two
# FMAs of the same row q and feature j for outputs p = 2m (X) and 2m + 1 (Y); they share x(q, j):
#   X: v_dual_fmac_f32 acc(q, 2m),     c(2m, j),  x(q, j)
#   Y: v_dual_fmac_f32 acc(q, 2m + 1), x(q, j),   c(2m + 1, j)
# VGPR banks (register % 4): acc(q, p) = v(128 + 8 q + p) -> bank p % 4; x(q, j) is the ds_load_b128
# quad of row q -> bank j. The coefficient banks below make every pair legal (destinations of
# opposite parity, src0 X / src0 Y and vsrc1 X / vsrc1 Y in different banks) with its five registers
# in four banks (one bank holds two of them; measured ~20 TFLOPS on gfx1151 for that pattern, against
# ~12 for single-issue v_fmac_f32). The 32 coefficients use exactly eight registers of each bank of
# v80..v111.
#
# x rows come from LDS (the caller's lane address, row q at offset 512 q): two 2-row register sets
# (v64..v71, v72..v79) rotate, each set's next rows requested as soon as its FMAs are issued.
# Usage: python tools/gen_hc_wide2_vopd.py > src/hip_hc_wide2_vopd.inc
ACC, XS, COEF = 128, 64, 80
ROWS, OUTS, SET = 16, 8, 2

def acc(q, p): return ACC + 8 * q + p
def xreg(q, j): return XS + 4 * SET * ((q // SET) % 2) + 4 * (q % SET) + j

def coef_bank(p, j):
    if p % 4 in (0, 1):
        return [2 + p % 2, 2 + p % 2, 3, 2][j]
    return [1, 0, p % 2, p % 2][j]

coef_reg = {}
used = {b: 0 for b in range(4)}
for p in range(OUTS):
    for j in range(4):
        b = coef_bank(p, j)
        coef_reg[(p, j)] = COEF + 4 * used[b] + b
        used[b] += 1
assert all(v == 8 for v in used.values()), used

def check_pair(q, j, p):
    x, y = (acc(q, p), coef_reg[(p, j)], xreg(q, j)), (acc(q, p + 1), xreg(q, j), coef_reg[(p + 1, j)])
    assert x[0] % 2 != y[0] % 2
    assert x[1] % 4 != y[1] % 4 and x[2] % 4 != y[2] % 4
    regs = {x[0], y[0], coef_reg[(p, j)], coef_reg[(p + 1, j)], xreg(q, j)}
    banks = [r % 4 for r in regs]
    assert len(regs) == 5 and len(set(banks)) == 4, (q, j, p, regs)

lines = []
def load_set(first):
    for q in range(first, first + SET):
        lines.append(f"ds_load_b128 v[{xreg(q, 0)}:{xreg(q, 3)}], %[lds] offset:{512 * q}")

SETS = ROWS // SET
load_set(0)
load_set(SET)
for s in range(SETS):
    # Sets still in flight after this one: the next set's loads.
    lines.append(f"s_waitcnt lgkmcnt({SET if s + 1 < SETS else 0})")
    # Feature-major over the set's rows: an accumulator's next FMA is 4 * SET pairs later.
    for j in range(4):
        for q in range(SET * s, SET * s + SET):
            for m in range(OUTS // 2):
                p = 2 * m
                check_pair(q, j, p)
                lines.append(f"v_dual_fmac_f32 v{acc(q, p)}, v{coef_reg[(p, j)]}, v{xreg(q, j)} :: "
                             f"v_dual_fmac_f32 v{acc(q, p + 1)}, v{xreg(q, j)}, v{coef_reg[(p + 1, j)]}")
    if s + 2 < SETS:
        load_set(SET * (s + 2))

acc_operands = ", ".join(f'"+{{v{acc(q, p)}}}"(acc[{8 * q + p}])' for q in range(ROWS) for p in range(OUTS))
coef_operands = ", ".join(f'"{{v{coef_reg[(p, j)]}}}"(c[{4 * p + j}])' for p in range(OUTS) for j in range(4))
clobbers = ", ".join(f'"v{r}"' for r in range(XS, XS + 8 * SET))
print("// Generated by tools/gen_hc_wide2_vopd.py; do not edit.")
print("__device__ __forceinline__ void hc_wide2_chunk(float (&acc)[128], const float (&c)[32], unsigned lds) {")
print('    asm volatile("' + "\\n\\t".join(lines) + '"')
print("        : " + acc_operands)
print("        : " + coef_operands + ", [lds] \"v\"(lds)")
print("        : " + clobbers + ', "memory");')
print("}")
