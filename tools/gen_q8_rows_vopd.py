#!/usr/bin/env python3
# Generates src/hip_q8_rows_vopd.inc: one chunk of the q8_rows wide coefficient kernel
# (4 outputs x 4 rows x 8 leaves = 128 FMAs) as hand-paired VOPD with pinned VGPRs,
# so that every FMA reads its three operands from three different VGPR banks
# (bank = register % 4):
#   accumulator (o, r, l) -> v(64 + (o * 4 + r) * 8 + l)       bank l
#   coefficient (o, l)    -> v(29 + o * 8 + l)  (scratch)      bank l + 1
#   activation  (r, l)    -> v(2 + 8 * (r % 2) + l)  (scratch) bank l + 2
#   raw BF16 row r word i -> v(192 + 16 * b + 4 * r + i)       bank i (raw buffer b = 0, 1)
#   FP32 activation (r, l) -> v(194 + 8 * r + l)  (the loaded rows themselves, bank l + 2)
# The chunk's coefficients are read from LDS inside the asm (two ds_load_b128 per
# output, issued first); row 0 runs output by output behind progressive
# s_waitcnt lgkmcnt so the FMAs start when the first output's coefficients land.
# Each FMA is v_fmac_f32 d = fma(c, x, d), the single-rounding FMA the sites'
# Site::fma compiles to (checked bitwise against the R1 kernels by the q8_rows
# projection test). Row r + 1's activations are widened (BF16: x[2i] = w_i << 16,
# x[2i+1] = w_i & 0xffff0000; FP32: copied) in the Y half of VOPD whose X half is an
# FMA of row r.
# Usage: python tools/gen_q8_rows_vopd.py > src/hip_q8_rows_vopd.inc
ACC, COEF, XB, RAW, XF = 64, 29, 2, 192, 194
FP32 = False

def acc(o, r, l): return ACC + (o * 4 + r) * 8 + l
def coef(o, l): return COEF + o * 8 + l
def x(r, l): return XF + 8 * r + l if FP32 else XB + 8 * (r % 2) + l
def fma(o, r, l): return f"v_dual_fmac_f32 v{acc(o, r, l)}, v{coef(o, l)}, v{x(r, l)}"

def widen_ops(r, bf16):
    """(dst register, operands after dst, raw source register, opcode) of row r."""
    ops = []
    if bf16:
        for i in range(4):
            w = RAW + 4 * r + i
            ops.append((x(r, 2 * i), f"16, v{w}", w, "lshlrev_b32"))
            ops.append((x(r, 2 * i + 1), f"0xffff0000, v{w}", w, "and_b32"))
    else:
        for i in range(8):
            w = RAW + 8 * r + i
            ops.append((x(r, i), f"v{w}", w, "mov_b32"))
    return ops

def fits(o, r, l, op):
    dst, rest, src, name = op
    if acc(o, r, l) % 2 == dst % 2: return False           # destinations: opposite parity
    if name == "mov_b32": return coef(o, l) % 4 != src % 4  # src0 halves
    return x(r, l) % 4 != src % 4                           # src1 halves

def output_group(o, r, widen):
    """VOPD lines for output o of row r, carrying the widening ops `widen` as Y halves."""
    left = [l for l in range(8)]
    lines = []
    for op in widen:
        for l in left:
            if fits(o, r, l, op):
                left.remove(l)
                lines.append(f"{fma(o, r, l)} :: v_dual_{op[3]} v{op[0]}, {op[1]}")
                break
        else:
            raise SystemExit(f"no partner for {op}")
    even = [l for l in left if l % 2 == 0]
    odd = [l for l in left if l % 2 == 1]
    assert len(even) == len(odd), (o, r, widen)
    for a, b in zip(even, odd):
        lines.append(f"{fma(o, r, a)} :: {fma(o, r, b)}")
    return lines

def chunk(bf16):
    lines = []
    # Coefficient quads: output o, plane q (leaves 4q..4q+3) at byte offset o * 1024 + q * 512.
    for o in range(4):
        for q in range(2):
            lines.append(f"ds_load_b128 v[{coef(o, 4 * q)}:{coef(o, 4 * q + 3)}], %[lds] offset:{o * 1024 + q * 512}")
    if bf16:
        for (dst, rest, src, op) in widen_ops(0, bf16): lines.append(f"v_{op} v{dst}, {rest}")
    for r in range(4):
        widen = widen_ops(r + 1, bf16) if r < 3 and bf16 else []
        per = len(widen) // 4 if widen else 0
        for o in range(4):
            if r == 0: lines.append(f"s_waitcnt lgkmcnt({6 - 2 * o})")
            lines += output_group(o, r, widen[o * per:(o + 1) * per])
    return lines

def emit(bf16, buf=0):
    global FP32, RAW
    FP32 = not bf16
    RAW = 192 + 16 * buf
    words = 16 if bf16 else 32
    outs = [f'"+{{v{acc(o, r, l)}}}"(v[{(o * 4 + r) * 8 + l}])' for o in range(4) for r in range(4) for l in range(8)]
    ins = [f'"{{v{(RAW if bf16 else XF) + i}}}"(w[{i}])' for i in range(words)] + ['[lds] "v"(lds)']
    clob = ", ".join(([f'"v{XB + i}"' for i in range(16)] if bf16 else []) + [f'"v{COEF + i}"' for i in range(32)] + ['"memory"'])
    body = "\\n\\t".join(chunk(bf16))
    name = "vopd_chunk" if buf == 0 else "vopd_chunk_b1"
    return (f"__device__ __forceinline__ void {name}(float (&v)[128], const unsigned (&w)[{words}], unsigned lds) {{\n"
            f"    asm volatile(\"{body}\"\n        : {', '.join(outs)}\n        : {', '.join(ins)}\n        : {clob});\n}}\n")

print("// Generated by tools/gen_q8_rows_vopd.py; do not edit.")
print(emit(True))
# Second raw buffer (v208..v223) for the variant that prefetches the next chunk's BF16 rows.
print(emit(True, 1))
print(emit(False))
