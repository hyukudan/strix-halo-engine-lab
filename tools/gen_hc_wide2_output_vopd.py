#!/usr/bin/env python3
# Generates src/hip_hc_wide2_output_vopd.inc: one rank step k of the wide HC output kernel
# (lane = one output feature; 4 streams x 32 rows = 128 gate chains per lane) as hand-paired VOPD.
#
# Every chain runs gate(s, t) = fma(low(t, k), c(s, k), gate(s, t)) in ascending k (v_dual_fmac_f32:
# the single-rounding FMA the C++ `gate += low * coefficient` contracts to). low(t, k) is the same in
# every lane (one row's low value), so it is an SGPR; a VOPD pair is the two streams 2m, 2m + 1 of one
# row, both reading that SGPR:
#   X: v_dual_fmac_f32 gate(2m, t),     s_low(t), c(2m)
#   Y: v_dual_fmac_f32 gate(2m + 1, t), s_low(t), c(2m + 1)
# Its four VGPRs sit in four different banks (register % 4), the pattern that runs at the full dual-issue
# rate on gfx1151 (~27 TFLOPS measured). Rows 0..15 keep their gates in banks 0/1 and read the
# coefficients from banks 2/3 (v122, v123, v126, v127); rows 16..31 keep theirs in banks 2/3 and read
# copies in banks 0/1 (v120, v121, v124, v125), made by two VOPD moves per step. The 128 gates fill
# v128..v255 (32 rows; the 16-row form keeps rows 0..7 / 8..15 that way in v128..v191).
ACC = 128
# Usage: python tools/gen_hc_wide2_output_vopd.py > src/hip_hc_wide2_output_vopd.inc
STREAMS = 4
COEF = {0: 122, 1: 123, 2: 126, 3: 127}
COPY = {0: 120, 1: 121, 2: 124, 3: 125}

def emit(rows):
    half = rows // 2
    def gate(s, t):
        if t < half: return ACC + 4 * (2 * t + s // 2) + s % 2
        return ACC + 4 * (2 * (t - half) + s // 2) + 2 + s % 2
    regs = sorted(gate(s, t) for s in range(STREAMS) for t in range(rows))
    assert regs == list(range(ACC, ACC + 4 * rows))
    lines = ["v_dual_mov_b32 v120, v122 :: v_dual_mov_b32 v121, v123", "v_dual_mov_b32 v124, v126 :: v_dual_mov_b32 v125, v127"]
    for t in range(rows):
        for m in range(STREAMS // 2):
            s0, s1 = 2 * m, 2 * m + 1
            c0, c1 = (COEF[s0], COEF[s1]) if t < half else (COPY[s0], COPY[s1])
            a0, a1 = gate(s0, t), gate(s1, t)
            assert a0 % 2 != a1 % 2 and len({a0 % 4, a1 % 4, c0 % 4, c1 % 4}) == 4
            lines.append(f"v_dual_fmac_f32 v{a0}, %[l{t}], v{c0} :: v_dual_fmac_f32 v{a1}, %[l{t}], v{c1}")
    gate_operands = ", ".join(f'"+{{v{gate(s, t)}}}"(g[{4 * t + s}])' for t in range(rows) for s in range(STREAMS))
    coef_operands = ", ".join(f'"{{v{COEF[s]}}}"(c{s})' for s in range(STREAMS))
    low_operands = ", ".join(f'[l{t}] "s"(low[{t}])' for t in range(rows))
    print(f"__device__ __forceinline__ void hc_wide2_output_step(float (&g)[{4 * rows}], float c0, float c1, float c2, float c3, const float (&low)[{rows}]) {{")
    print('    asm volatile("' + "\\n\\t".join(lines) + '"')
    print("        : " + gate_operands)
    print("        : " + coef_operands + ", " + low_operands)
    print('        : "v120", "v121", "v124", "v125");')
    print("}")

print("// Generated by tools/gen_hc_wide2_output_vopd.py; do not edit.")
emit(32)
emit(16)
